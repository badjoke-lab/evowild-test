def paint_end(base,width,center,kind,reverse):
    im=Image.fromarray(base.copy())
    draw=ImageDraw.Draw(im)
    for row in END_PAINT.get(kind,'').strip().splitlines():
        color,path=row.split(' ',1)
        if reverse and kind=='neck':color={'slate':'steel','steel':'rim','blue':'shadow'}[color]
        pts=[]
        for k,y in points(path):
            j=int(np.clip(round((GROUND-y)/SY-.5),0,NY-1))
            u=center[j]+k*width[j]*(-1 if reverse else 1)
            pts.append((round((u-Z0)/SZ-.5),j))
        draw.polygon(pts,fill=KEY[color])
    return np.where(base,np.asarray(im),0).astype('u1')
