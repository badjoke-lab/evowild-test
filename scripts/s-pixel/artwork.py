def add(name,side,top,front,rear,material='hide',offset=0, center=None):
    # Top stations control width along the length. Front and rear profiles
    # independently bound width per height, even in partly hidden parts.
    parts=dict(name=name,side=side_bitmap(side),top=profile(top),front=profile(front),
               rear=profile(rear),mat=material,offset=offset,center=profile(center) if center else None)
    PARTS.append(parts)
    return parts

