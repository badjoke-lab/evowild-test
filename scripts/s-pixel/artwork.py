def points(s):
    v = [float(i) for i in s.replace(',',' ').split()]
    return list(zip(v[::2],v[1::2]))
def profile(s):
    return np.array(points(s)).T
def side_bitmap(drawing):
    im=Image.new('L',(NX,NY))
    draw=ImageDraw.Draw(im)
    for row in drawing.strip().splitlines():
        color, path = row.strip().split(' ',1)
        vertices=[(round((x-X0)/SX-.5),round((GROUND-y)/SY-.5)) for x,y in points(path)]
        draw.polygon(vertices, fill=KEY[color])
    return np.asarray(im)
